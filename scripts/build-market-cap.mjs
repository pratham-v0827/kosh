#!/usr/bin/env node
// Rebuild Kosh's market-cap table from AMFI's half-yearly list (run each January and July).
//
//   1. Download the Excel list from https://www.amfiindia.com/otherdata/categorisation-of-stocks
//   2. pnpm data:market-cap "C:\Users\you\Downloads\AverageMarketCapitalization30Jun2026.xlsx"
//
// Writes packages/core/src/data/amfi-market-cap.ts (the top 250 companies: ISIN, NSE and BSE
// symbols, name). The app never downloads anything; it only reads that committed file.
// The list is public data. The script fails if the file's layout or SEBI's 100 / 250 rule changed.
import { readFileSync, statSync, writeFileSync } from 'node:fs';
import { registerHooks } from 'node:module';
import { fileURLToPath } from 'node:url';
import prettier from 'prettier';

// The parsers package uses extensionless relative imports (resolved by its bundler and vitest).
registerHooks({
  resolve(specifier, context, next) {
    try {
      return next(specifier, context);
    } catch (e) {
      if (!specifier.startsWith('.')) throw e;
      try {
        return next(`${specifier}.ts`, context);
      } catch {
        return next(`${specifier}/index.ts`, context);
      }
    }
  },
});
const { readWorkbook, DEFAULT_SHEET_LIMITS } =
  await import('../packages/parsers/src/sheets/index.ts');
const { readAmfiMarketCap } = await import('../packages/parsers/src/amfi-market-cap.ts');

const file = process.argv[2];
if (!file) {
  console.error('Usage: pnpm data:market-cap <path-to-AMFI-list.xlsx>');
  process.exit(2);
}
if (statSync(file).size > 20 * 1024 * 1024) {
  console.error('That file is larger than 20 MB; AMFI’s list is under 1 MB.');
  process.exit(2);
}

// About 5,400 companies: more rows than a broker statement, so a higher row limit than uploads get.
const limits = { ...DEFAULT_SHEET_LIMITS, maxRows: 20000 };
const list = readAmfiMarketCap(readWorkbook(new Uint8Array(readFileSync(file)), limits));
const out = fileURLToPath(new URL('../packages/core/src/data/amfi-market-cap.ts', import.meta.url));
const source = `// Generated by scripts/build-market-cap.mjs from AMFI's list of average market capitalisation
// for the six months ended ${list.asOf} (${list.listed} listed companies). Do not edit by hand:
// download the next list and run "pnpm data:market-cap <file>".
// Source: https://www.amfiindia.com/otherdata/categorisation-of-stocks

/** [ISIN, NSE symbol, BSE symbol, company name] */
export type AmfiCompany = readonly [string, string | null, string | null, string];

export const AMFI_MARKET_CAP: {
  /** Last day of the six-month period. */
  asOf: string;
  listed: number;
  /** Ranks 1–250 in order: 1–100 large cap, 101–250 mid cap. */
  top250: readonly AmfiCompany[];
} = {
  asOf: ${JSON.stringify(list.asOf)},
  listed: ${list.listed},
  top250: [
${list.top250.map((c) => `    ${JSON.stringify(c)},`).join('\n')}
  ],
};
`;
const options = (await prettier.resolveConfig(out)) ?? {};
writeFileSync(out, await prettier.format(source, { ...options, filepath: out }));
console.log(
  `Wrote ${list.top250.length} companies (period ended ${list.asOf}, ${list.listed} listed) to ${out}`,
);
